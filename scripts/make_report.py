"""Render release/RESULTS.md and copy small public artifacts into release/ from actual run outputs.

Usage: python scripts/make_report.py [--data data/norcal] [--output output] [--release release]
Every number in RESULTS.md is read from a generated file; nothing is typed by hand.
"""
import argparse
import json
import shutil
from pathlib import Path

import pandas as pd


def f(v, d=4):
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return 'n/a'
    if isinstance(v, float) and v.is_integer() and abs(v) >= 1:
        return f'{int(v):,}' if abs(v) >= 10000 else str(int(v))
    if isinstance(v, float):
        return f'{v:.{d}f}'
    if isinstance(v, int) and not isinstance(v, bool) and abs(v) >= 10000:
        return f'{v:,}'
    return str(v)


def table(rows, cols, headers=None):
    headers = headers or cols
    out = ['| ' + ' | '.join(headers) + ' |', '|' + '---|' * len(cols)]
    for r in rows:
        out.append('| ' + ' | '.join(f(r.get(c)) for c in cols) + ' |')
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--data', default='data/norcal')
    ap.add_argument('--output', default='output')
    ap.add_argument('--release', default='release')
    a = ap.parse_args()
    data, out, rel = Path(a.data), Path(a.output), Path(a.release)
    rel.mkdir(exist_ok=True)
    ing = json.loads((data / 'interim' / 'ingest_report.json').read_text())
    cov = json.loads((data / 'dataset' / 'coverage_report.json').read_text())
    split = json.loads((out / 'splits' / 'split_manifest.json').read_text())
    frozen = json.loads((out / 'frozen_champion.json').read_text())
    board = pd.read_csv(out / 'validation_leaderboard.csv')
    test = json.loads((out / 'test_results.json').read_text()) if (out / 'test_results.json').exists() else None
    vint = json.loads((out / 'vintage_check.json').read_text()) if (out / 'vintage_check.json').exists() else None
    L = ['# FireRisk Open v0.2: measured results (auto-generated)', '',
         f'Generated by `scripts/make_report.py` from files in `{data}` and `{out}`. '
         'Research hindcast only: **not for emergency, evacuation, suppression or dispatch decisions.**', '',
         '## 1. Real-data ingest', '',
         f"Region bbox {ing['bbox']} at {ing['step']}°, issue dates {ing['issue_start']} → {ing['issue_end']}. "
         f"FIRMS fetch window {ing['fire_window']} over padded bbox {ing['padded_fire_bbox']}. "
         f"Raw files: {ing['raw_files']}; downloads in final run: {ing['network_downloads_this_run']}; "
         f"cache hits: {ing['cache_hits_this_run']}. Full list with SHA-256: `release/ingest_manifest.json`.", '',
         table(ing['firms_per_year'], ['year', 'regional_rows', 'national_rows', 'distinct_days', 'first_acq_date',
                                       'last_acq_date', 'version_values']), '',
         f"FIRMS day status (national NOAA-20 counts): {ing['firms_day_status_counts']}.", '',
         table(ing['firms_problem_days'], ['date', 'n_day', 'n_night', 'n_all', 'status']), '',
         f"ERA5 weather: {json.dumps(ing['weather'])}", '',
         '## 2. Dataset', '',
         f"`{cov['dataset_file']}`: {cov['rows']:,} cell-days × {cov['columns']} columns, SHA-256 `{cov['sha256']}`. "
         f"Land fraction min {cov['land_fraction_min']}; cell area {cov['cell_area_km2_range']} km² (not equal-area).", '',
         table([{'reason': k, 'rows': v} for k, v in cov['row_accounting'].items()], ['reason', 'rows']), '',
         'Primary-analysis rows by target year:', '',
         table(cov['primary_by_target_year'], ['year', 'rows', 'positives', 'prevalence', 'cloud_obscured_share',
                                               'issue_day_detection_share_of_positives']), '',
         f"Share of primary positives that already had a detection on the (unknown-at-issue) issue day: "
         f"{f(cov['primary_positive_share_with_issue_day_detection'])}.", '',
         '## 3. Splits (by target date, 32-day embargo)', '',
         table([{'split': k, **v} for k, v in split['summary'].items()],
               ['split', 'rows', 'positives', 'negatives', 'prevalence', 'distinct_positive_events', 'cells',
                'target_date_min', 'target_date_max']), '',
         f"Pairwise key overlap (must be 0): {split['pairwise_key_overlap']}. Chronology: {split['chronology']}.", '',
         '## 4. Validation leaderboard (best config per model × feature set; selection on validation AP)', '',
         table(board.to_dict(orient='records'),
               ['model', 'feature_set', 'val_average_precision', 'val_roc_auc', 'val_brier', 'val_brier_crossfit_isotonic',
                'val_balanced_accuracy', 'val_accuracy', 'val_precision', 'val_recall', 'val_f1', 'val_threshold']), '',
         f"Validation prevalence: {f(board['val_prevalence'].iloc[0])}. Thresholds maximise validation F1 on "
         "uncalibrated scores (in-sample, optimistic). Brier for raw scores of class-weighted models is not comparable; "
         "use the cross-fitted isotonic Brier column.", '',
         f"Highest validation balanced accuracy: {board.loc[board.val_balanced_accuracy.idxmax(), 'model']} / "
         f"{board.loc[board.val_balanced_accuracy.idxmax(), 'feature_set']} = {f(board.val_balanced_accuracy.max())}. "
         f"Highest validation accuracy: {board.loc[board.val_accuracy.idxmax(), 'model']} = {f(board.val_accuracy.max())} "
         "(majority-class accuracy shows why accuracy is not the selection criterion).", '',
         f"**Champion (frozen {frozen['frozen_at_utc']}):** `{frozen['champion']['key']}` with params "
         f"`{json.dumps(frozen['champion']['params'])}`, validation AP {f(frozen['champion']['validation_average_precision'])}, "
         f"calibrated threshold {f(frozen['decision_threshold_calibrated'])}.", '']
    if test:
        c = test['champion_test']
        comp = test['calibrated_comparators_test']
        L += ['## 5. One-time held-out test (targets 2024-02-02 → 2025-12-31)', '',
              f"Evaluated {test['evaluated_at_utc']} after freezing.", '',
              table([{'model': k, **v} for k, v in comp.items()],
                    ['model', 'n', 'positives', 'prevalence', 'average_precision', 'roc_auc', 'brier', 'accuracy',
                     'balanced_accuracy', 'precision', 'recall', 'f1', 'threshold']), '',
              f"Champion confusion matrix: {c['confusion_matrix']}.", '',
              '95% bootstrap CIs (resampling ISO weeks):', '',
              '```json', json.dumps(test['bootstrap_ci95_week_clusters'], indent=1), '```', '',
              '95% bootstrap CIs (resampling cells):', '',
              '```json', json.dumps(test['bootstrap_ci95_cell_clusters'], indent=1), '```', '',
              'By target year:', '',
              table([{'year': k, **v} for k, v in test['test_by_target_year'].items()],
                    ['year', 'n', 'positives', 'prevalence', 'average_precision', 'roc_auc', 'brier', 'balanced_accuracy']), '',
              'Champion reliability (test, calibrated):', '',
              table(c['reliability'], ['bin', 'n', 'mean_predicted', 'observed_rate']), '',
              '### All frozen candidates on the test split (reported, not used for selection)', '',
              table(pd.read_csv(out / 'test_leaderboard_frozen_candidates.csv').to_dict(orient='records'),
                    ['model', 'feature_set', 'test_average_precision', 'test_roc_auc', 'test_balanced_accuracy',
                     'test_accuracy', 'test_f1']), '',
              '### Sensitivity (reporting only)', '']
        for name, d in test['sensitivity'].items():
            L += [f'**{name}**', '', table([{'model': k, **v} for k, v in d.items()],
                                           ['model', 'n', 'positives', 'average_precision', 'roc_auc', 'brier']), '']
        L += ['### Spatial hold-out (champion config retrained without each 2°×2° block)', '',
              table([{'block': b, 'held_out_AP': v.get('held_out_model', {}).get('average_precision'),
                      'in_domain_AP': v.get('in_domain_champion_same_rows', {}).get('average_precision'),
                      'climatology_wo_block_AP': v.get('climatology_without_block (month-rate fallback)', {}).get('average_precision'),
                      'positives': v.get('held_out_model', {}).get('positives'), 'n': v.get('held_out_model', {}).get('n')}
                     for b, v in test['spatial_holdout'].items()],
                    ['block', 'n', 'positives', 'held_out_AP', 'in_domain_AP', 'climatology_wo_block_AP']), '',
              '### Error analysis', '',
              f"Missed positives that had a detection on the issue day: {f(test['error_analysis']['missed_positive_share_with_issue_day_detection'])}.", '',
              table(test['error_analysis']['recall_by_target_month'], ['month', 'positives', 'recall']), '',
              'Highest-probability false positives:', '',
              table(test['error_analysis']['top_false_positives'], ['cell_id', 'target_date', 'probability',
                                                                     'target_cloud_obscured_proxy', 'detection_on_issue_day']), '',
              'Largest missed detections (by next-day count):', '',
              table(test['error_analysis']['largest_missed_detections'], ['cell_id', 'target_date', 'probability',
                                                                          'target_nextday_count', 'detection_on_issue_day']), '']
        reg_val = pd.read_csv(out / 'regression_validation_leaderboard.csv')
        reg_test = test.get('regression_log1p_count_test', {})
        L += ['## 6. Secondary continuous target: log1p(next-day detection count)', '',
              'Same rows/splits. Count data are zero-inflated; this is a secondary analysis, not a probability model.', '',
              table([{**r, **{f'test_{k}': v for k, v in reg_test.get(r['model'], {}).items()}}
                     for r in reg_val.to_dict(orient='records')],
                    ['model', 'val_MAE', 'val_MSE', 'val_RMSE', 'val_R2', 'test_MAE', 'test_MSE', 'test_RMSE', 'test_R2']), '']
    imp = pd.read_csv(out / 'champion_permutation_importance_validation.csv')
    L += ['## 7. Champion permutation importance (validation AP drop)', '',
          table(imp.to_dict(orient='records'), ['feature', 'perm_importance_val_ap_mean', 'perm_importance_val_ap_std']), '']
    if vint:
        L += ['## 8. Operational-vintage check (frozen model, after the test)', '',
              table([{'variable': k, **v} for k, v in vint['weather_variable_differences'].items()],
                    ['variable', 'n_cell_days', 'bias_hf_minus_era5', 'mae', 'corr']), '',
              '```json', json.dumps({k: vint[k] for k in ['weather_vintage_model_eval', 'fire_label_agreement_typed_vs_typeless',
                                                          'typeless_fire_model_eval', 'not_measured']}, indent=1), '```', '']
    (rel / 'RESULTS.md').write_text('\n'.join(L) + '\n')
    for src, dst in [(data / 'dataset' / cov['dataset_file'], cov['dataset_file']),
                     (data / 'dataset' / 'data_dictionary.csv', 'data_dictionary.csv'),
                     (data / 'dataset' / 'coverage_report.json', 'coverage_report.json'),
                     (data / 'manifest.json', 'ingest_manifest.json'),
                     (data / 'interim' / 'ingest_report.json', 'ingest_report.json'),
                     (data / 'interim' / 'firms_day_status.csv', 'firms_day_status.csv'),
                     (out / 'splits' / 'split_manifest.json', 'split_manifest.json'),
                     (out / 'validation_leaderboard.csv', 'validation_leaderboard.csv'),
                     (out / 'validation_grid_all_configs.csv', 'validation_grid_all_configs.csv'),
                     (out / 'frozen_champion.json', 'frozen_champion.json'),
                     (out / 'test_results.json', 'test_results.json'),
                     (out / 'test_leaderboard_frozen_candidates.csv', 'test_leaderboard_frozen_candidates.csv'),
                     (out / 'test_predictions.parquet', 'test_predictions.parquet'),
                     (out / 'regression_validation_leaderboard.csv', 'regression_validation_leaderboard.csv'),
                     (out / 'champion_permutation_importance_validation.csv', 'champion_permutation_importance_validation.csv'),
                     (out / 'vintage_check.json', 'vintage_check.json')]:
        if src.exists():
            shutil.copy2(src, rel / dst)
    m = json.loads((rel / 'ingest_manifest.json').read_text())
    for e in m:   # make paths repo-relative and drop local absolute prefixes
        e['file'] = str(Path(e['file']).relative_to(Path(e['file']).parents[2])) if 'raw' in e['file'] else e['file']
    (rel / 'ingest_manifest.json').write_text(json.dumps(m, indent=1) + '\n')
    print(f'wrote {rel}/RESULTS.md')


if __name__ == '__main__':
    main()

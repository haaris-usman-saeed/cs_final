"""Render release_v3/RESULTS_v3.md from generated v0.3 files and copy public artefacts. No hand-typed numbers.

Usage: python scripts/make_report_v3.py [--data data/v03] [--output output_v3] [--release release_v3]
Per-region bootstrap CIs are computed here from the saved one-time test predictions (reporting only; no refit).
"""
import argparse
import json
import shutil
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score


def f(v, d=4):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return 'n/a'
    if isinstance(v, (bool, np.bool_)):
        return str(bool(v))
    if isinstance(v, (int, np.integer)):
        return f'{v:,}' if abs(v) >= 10000 else str(v)
    if isinstance(v, float):
        return f'{v:.{d}f}'
    return str(v)


def table(rows, cols, headers=None):
    out = ['| ' + ' | '.join(headers or cols) + ' |', '|' + '---|' * len(cols)]
    out += ['| ' + ' | '.join(f(r.get(c)) for c in cols) + ' |' for r in rows]
    return '\n'.join(out)


def ci(v):
    return f'{v[0]:.3f}–{v[1]:.3f}'


def region_boot(pred: pd.DataFrame, a: str, b: str, n=1000, seed=17):
    rng = np.random.default_rng(seed)
    out = {}
    for reg, g in pred.groupby('region'):
        y = g['target_nextday_detection'].astype(int).to_numpy()
        wk = pd.to_datetime(g['target_date']).dt.strftime('%G-W%V').to_numpy()
        uc, inv = np.unique(wk, return_inverse=True)
        mem = [np.flatnonzero(inv == i) for i in range(len(uc))]
        pa, pb = g[a].to_numpy(), g[b].to_numpy()
        apa, apb, dd = [], [], []
        for _ in range(n):
            ix = np.concatenate([mem[i] for i in rng.integers(0, len(uc), len(uc))])
            if y[ix].sum() == 0:
                continue
            x1, x2 = average_precision_score(y[ix], pa[ix]), average_precision_score(y[ix], pb[ix])
            apa.append(x1), apb.append(x2), dd.append(x1 - x2)
        out[reg] = {'n': len(g), 'positives': int(y.sum()), 'base_rate': float(y.mean()),
                    'ap_a': float(average_precision_score(y, pa)), 'ap_a_ci': ci(np.percentile(apa, [2.5, 97.5])),
                    'ap_b': float(average_precision_score(y, pb)), 'ap_b_ci': ci(np.percentile(apb, [2.5, 97.5])),
                    'delta_ci': ci(np.percentile(dd, [2.5, 97.5])), 'share_delta_gt_0': float(np.mean(np.array(dd) > 0))}
    return out


